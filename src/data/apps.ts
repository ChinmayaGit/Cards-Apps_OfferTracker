const appById = new Map(APP_LIST.map((a) => [a.id, a]))
let appOfferOverlay: Partial<Record<PayAppId, Offer[]>> = {}

function mergeOffers(base: Offer[], extra: Offer[]): Offer[] {
  const byId = new Map(base.map((o) => [o.id, o]))
  for (const o of extra) byId.set(o.id, o)
  const seen = new Set<string>()
  const out: Offer[] = []
  for (const offer of base) {
    out.push(byId.get(offer.id)!)
    seen.add(offer.id)
  }
  for (const offer of extra) {
    if (!seen.has(offer.id)) {
      out.push(offer)
      seen.add(offer.id)
    }
  }
  return out
}

export const PAY_APP_IDS: PayAppId[] = APP_LIST.map((a) => a.id)

export function applyAppOfferOverlay(next: Partial<Record<PayAppId, Offer[]>>): void {
  appOfferOverlay = next
}

export function getApp(id: string): PayApp | undefined {
  const app = appById.get(id as PayAppId)
  if (!app) return undefined
  const extra = appOfferOverlay[app.id]
  if (!extra?.length) return app
  return { ...app, offers: mergeOffers(app.offers, extra) }
}

export function getApps(): PayApp[] {
  return PAY_APP_IDS.map((id) => getApp(id)!).filter(Boolean)
}
