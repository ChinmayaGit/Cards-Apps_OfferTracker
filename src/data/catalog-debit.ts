import type { CardProduct, Network, Offer } from '../types'
import { NOTE, rupay, visaMc } from './pay'

function o(partial: Offer): Offer {
  return partial
}

function everyday(id: string, network: Network, extras: string[] = []): Offer {
  const isRupay = network === 'RuPay'
  return o({
    id: `${id}-daily`,
    title: 'POS, tap, online — UPI is the account',
    category: 'upi',
    headline: isRupay
      ? 'Swipe/tap/online with this RuPay debit. Scanning UPI uses the same account, not a credit line. Debit lounge/movie perks almost never follow a QR.'
      : 'Swipe/tap/online with this debit card. UPI QR does not charge Visa/Mastercard debit — it hits the account with no debit-card offer.',
    howToUse: [
      'In-store: chip, swipe or contactless tap on the terminal.',
      'Online: choose Debit card and this network (Visa / Mastercard / RuPay).',
      'Daily QR: use GPay/PhonePe on the bank account. That is not this plastic.',
      'Phone tap: only if the bank added this debit card to Google Pay / Apple Pay NFC.',
    ],
    where: ['POS', 'Contactless terminals', 'e-commerce', 'ATM', 'UPI (account)'],
    payment: isRupay ? rupay() : visaMc({ upi: 'no' }),
    paymentNotes: {
      swipe: NOTE.swipePos,
      tapCard: 'Contactless debit where the terminal and card support it (PIN may still be asked above a limit).',
      phoneNfc: NOTE.debitPhone,
      upi: isRupay ? NOTE.debitUpiRupay : NOTE.debitUpiVisa,
      online: 'Debit card checkout + 3-D Secure. Do not pick UPI if you wanted a debit-card offer.',
    },
    hidden: [
      'Credit-card BOGO, SmartBuy multipliers and RuPay-credit UPI cashback do not apply on debit.',
      'UPI / wallet / EMI / ATM usually do not count toward debit lounge spend gates.',
      ...extras,
    ],
    source: 'Issuer debit MITC (2026)',
  })
}

function loungeVoucher(
  id: string,
  title: string,
  headline: string,
  hidden: string[],
  cap: string,
  source: string,
): Offer {
  return o({
    id: `${id}-lounge`,
    title,
    category: 'lounge',
    headline,
    howToUse: [
      'Meet the spend gate on this debit card (POS/e-com — not UPI).',
      'Claim the SMS/email voucher if your bank moved off card-swipe lounge (HDFC from 10 Jan 2026).',
      'Show voucher + carry plastic. Phone NFC and UPI will not check you in.',
    ],
    where: ['Listed domestic airport lounges'],
    payment: { swipe: 'maybe', tapCard: 'no', phoneNfc: 'no', upi: 'no', online: 'no' },
    paymentNotes: {
      swipe: 'Many banks dropped swipe-in during 2026. HDFC Visa/MC debit is voucher-only from 10 Jan 2026.',
      tapCard: 'Lounge tap usually fails the new voucher programmes.',
      phoneNfc: 'No.',
      upi: 'UPI cannot enter a lounge and does not count as lounge spend.',
      online: 'Claim voucher online; entry is at the airport.',
    },
    hidden,
    cap,
    source,
  })
}

