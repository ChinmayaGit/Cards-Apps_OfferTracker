export const PRODUCTS: CardProduct[] = [...CORE_PRODUCTS, ...MORE_PRODUCTS, ...DEBIT_PRODUCTS]

const productById = new Map(PRODUCTS.map((p) => [p.id, p]))
const bankById = new Map(BANKS.map((b) => [b.id, b]))

export function getProduct(id: string): CardProduct | undefined {
  return productById.get(id)
}

export function getBank(id: string): Bank | undefined {
  return bankById.get(id)
}

export function productsForBank(bankId: string, kind?: CardProduct['kind']): CardProduct[] {
  return PRODUCTS.filter((p) => p.bankId === bankId && (!kind || p.kind === kind)).sort((a, b) => {
    if (a.kind !== b.kind) return a.kind === 'debit' ? -1 : 1
    return a.name.localeCompare(b.name)
  })
}

export function searchProducts(query: string, kind?: CardProduct['kind']): CardProduct[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return PRODUCTS.filter((p) => {
    if (kind && p.kind !== kind) return false
    const bank = bankById.get(p.bankId)
    const blob = [p.name, p.kind, p.network, p.blurb, bank?.name, bank?.short, ...(p.aliases ?? [])]
      .join(' ')
      .toLowerCase()
    return blob.includes(q)
  }).slice(0, 24)
}

export function banksWithKind(kind?: CardProduct['kind']): Bank[] {
  const ids = new Set(
    PRODUCTS.filter((p) => !kind || p.kind === kind).map((p) => p.bankId),
  )
  return BANKS.filter((b) => ids.has(b.id))
}

export function bankCardCounts(bankId: string): { credit: number; debit: number } {
  const list = PRODUCTS.filter((p) => p.bankId === bankId)
  return {
    credit: list.filter((p) => p.kind === 'credit').length,
    debit: list.filter((p) => p.kind === 'debit').length,
  }
}
